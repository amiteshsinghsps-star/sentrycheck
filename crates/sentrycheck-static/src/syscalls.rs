pub fn subsystem(name: &str) -> Option<&'static str> {
    if name.starts_with("io_uring") || name.contains("liburing") {
        Some("io_uring")
    } else if name == "bpf"
        || name.starts_with("bpf_")
        || name.contains("libbpf")
        || name.contains("cilium/ebpf")
    {
        Some("ebpf")
    } else if name.contains("cgroup") {
        Some("cgroup")
    } else {
        None
    }
}
